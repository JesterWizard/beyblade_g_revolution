def tile_words(rows):
    words = []
    for row in rows:
        assert len(row) == 8, row
        w = 0
        for x, ch in enumerate(row):
            if ch != ".":
                w |= int(ch, 16) << (4 * x)
        words.append(w)
    return words

def main():
    out = sys.argv[1]
    lines = [
        "/* Generated by gen_weather_gfx.py. */",
        '#include "debug_menu.h"',
        "",
        "const u32 gWeatherTiles[WEATHER_TILES][8] = {",
    ]
    for n in range(len(TILES)):
        words = ", ".join("0x%08X" % w for w in tile_words(TILES[n]))
        lines.append("    { %s }," % words)
    lines += ["};", "", "const u16 gWeatherPalette[16] = {"]
    cols = [rgb(*PALETTE.get(i, (0, 0, 0))) for i in range(16)]
    lines.append("    " + ", ".join("0x%04X" % c for c in cols))
    lines += ["};", ""]
    open(out, "w").write("\n".join(lines))

main()
