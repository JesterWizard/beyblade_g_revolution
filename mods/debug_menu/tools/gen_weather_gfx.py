#!/usr/bin/env python3
"""Generate src/weather_gfx.c: the particle art of the weather entry.

Nine 8x8 4bpp OBJ tiles and one 16-colour palette, drawn here as text. Each
character is a palette index ('.' is transparent, 0-9/a-f are the colours
below); a tile row is read left to right.

usage: gen_weather_gfx.py <out.c>
"""
import sys

def rgb(r, g, b):
    return r | (g << 5) | (b << 10)

